import { spawnSync } from 'node:child_process';
import { basename } from 'node:path';
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
const baseline = JSON.parse(readFileSync('ci/baseline-cases.json', 'utf8'));
const plans = [
  ['logic', 'playwright.logic.config.ts', {}],
  ['http', 'playwright.integration.config.ts', {}],
  ['browser-contracts', 'playwright.ci.config.ts', { CI_BROWSER_LAYER: 'contracts' }],
  ['browser-experience', 'playwright.ci.config.ts', { CI_BROWSER_LAYER: 'experience' }],
];
const permittedSkips = JSON.parse(readFileSync('ci/conditional-skips.json', 'utf8'));
const allowed = new Set(permittedSkips.map((entry) => JSON.stringify([entry.file, entry.line])));
const seenSkips = new Set();
for (const directory of ['tests/logic', 'tests/integration', 'tests/e2e']) {
  for (const file of readdirSync(directory, { recursive: true }).filter((file) => file.endsWith('.spec.ts'))) {
    const text = readFileSync(`${directory}/${file}`, 'utf8');
    if (/\b(?:test|describe)(?:\.describe)?\.(?:only|fixme)\s*\(/.test(text)) throw new Error(`Focused/disabled tests: ${file}`);
    for (const line of text.split('\n').filter((line) => /\b(?:test|describe)(?:\.describe)?\.skip\s*\(/.test(line))) {
      const identity = JSON.stringify([file, line.trim()]);
      if (!allowed.has(identity)) throw new Error(`Unreviewed skip: ${file}: ${line.trim()}`);
      seenSkips.add(identity);
    }
  }
}
if (seenSkips.size !== allowed.size) throw new Error('Conditional skip inventory changed; review and update the contract explicitly');
plans.push(['unpartitioned-current', 'playwright.config.ts', {}]);
const collected = [];
for (const [layer, config, env] of plans) {
  const child = spawnSync(process.execPath, ['node_modules/@playwright/test/cli.js', 'test', '--config', config, '--list', '--reporter=json'], {
    encoding: 'utf8', env: { ...process.env, ...env }, maxBuffer: 20 * 1024 * 1024,
  });
  if (child.status !== 0) throw new Error(`${layer} collection failed: ${child.stderr}\n${child.stdout}`);
  const report = JSON.parse(child.stdout);
  if (report.errors?.length) throw new Error(JSON.stringify(report.errors));
  const visit = (suite, parents = []) => {
    const titles = suite.title && !suite.title.endsWith('.spec.ts') ? [...parents, suite.title] : parents;
    for (const spec of suite.specs || []) for (const test of spec.tests) collected.push({
      file: basename(spec.file), title: [...titles, spec.title], project: test.projectName,
      expected: test.expectedStatus, layer,
    });
    for (const nested of suite.suites || []) visit(nested, titles);
  };
  for (const suite of report.suites) visit(suite);
}
const cases = collected.filter((c) => c.layer !== 'unpartitioned-current');
const key = (c) => JSON.stringify([c.file, c.title, c.project === 'logic' ? 'chromium' : c.project, c.expected]);
const current = new Map();
for (const c of cases) {
  if (current.has(key(c))) throw new Error(`Duplicate case ownership: ${key(c)}`);
  current.set(key(c), c);
}
for (const c of collected.filter((c) => c.layer === 'unpartitioned-current')) {
  if (!current.has(key(c))) throw new Error(`Current browser test has no layer owner: ${key(c)}`);
}
const missing = baseline.filter((c) => !current.has(key(c)));
if (missing.length) throw new Error(`Lost baseline coverage:\n${JSON.stringify(missing, null, 2)}`);
const old = new Set(baseline.map(key));
const additions = cases.filter((c) => !old.has(key(c)));
// New cases are permitted and collected in full; no path selection can drop them.
const mapping = baseline.map((c) => ({ ...c, layer: current.get(key(c)).layer, newProject: current.get(key(c)).project }));
mkdirSync('output/ci-migration/coverage', { recursive: true });
writeFileSync('output/ci-migration/coverage/mapping.json', JSON.stringify({ baseline: mapping, additions }, null, 2) + '\n');
const counts = Object.fromEntries(plans.filter(([layer]) => layer !== 'unpartitioned-current').map(([layer]) => [layer, cases.filter((c) => c.layer === layer).length]));
console.log(JSON.stringify({ baseline: baseline.length, current: cases.length, additions: additions.length, counts }, null, 2));
if (process.argv.includes('--write-table')) {
  const rows = [...new Set(baseline.map((c) => c.file))].sort().map((file) => {
    const entries = mapping.filter((c) => c.file === file);
    return `| ${file} | ${entries.filter((c) => c.project === 'chromium').length} | ${entries.filter((c) => c.project === 'webkit-responsive').length} | ${[...new Set(entries.map((c) => c.layer))].join(', ')} |`;
  });
  writeFileSync('docs/ci-coverage-migration.md', `# CI coverage migration\n\nFrozen baseline: caee1e38104330b055b0797df8e6078849400382. Counts are expanded execution identities, not just test declarations. Generated by \`npm run ci:coverage -- --write-table\`. Full case-level mapping is emitted as an Actions artifact; baseline identities are versioned in \`ci/baseline-cases.json\`.\n\n| Old file | Chromium | WebKit | New owner |\n| --- | ---: | ---: | --- |\n${rows.join('\n')}\n\nServer coverage: all 35 \`*.test.ts\` files plus \`run.ts\` are explicitly assigned in \`ci/server-suites.json\`; the runner rejects missing or duplicate owners. The original 85-check runner and the 1+20+100 full-game checks remain intact. Configuration, audit, source checks, Docker builds, and real SIGTERM/recovery remain mandatory (see CI architecture).\n`);
}
