import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { copyFile, mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { extname, join, parse, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const sourceDirectory = join(root, "assets/audio/quick-phrases");
const publicDirectory = join(root, "client/public/quick-phrases");
const clientManifest = join(root, "client/src/generated/quickPhrases.ts");
const serverManifest = join(root, "server/src/generated/quickPhrases.ts");
const supportedExtensions = new Set([".aac", ".m4a", ".mp3", ".ogg", ".wav"]);

function probeSeconds(file) {
  try {
    const output = execFileSync("ffprobe", [
      "-v", "error", "-show_entries", "format=duration", "-of", "default=noprint_wrappers=1:nokey=1", file,
    ], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
    const seconds = Number.parseFloat(output.trim());
    if (Number.isFinite(seconds) && seconds > 0) return seconds;
  } catch {}

  try {
    const output = execFileSync("afinfo", [file], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
    const match = output.match(/estimated duration:\s*([\d.]+)\s*sec/i);
    const seconds = Number.parseFloat(match?.[1] ?? "");
    if (Number.isFinite(seconds) && seconds > 0) return seconds;
  } catch {}

  return 3.75;
}

const entries = (await readdir(sourceDirectory, { withFileTypes: true }))
  .filter((entry) => entry.isFile() && !entry.name.startsWith(".") && supportedExtensions.has(extname(entry.name).toLowerCase()))
  .sort((left, right) => left.name.localeCompare(right.name, "zh-Hans-CN"));

const labels = new Set();
const phrases = entries.map((entry) => {
  const normalizedName = entry.name.normalize("NFC");
  const extension = extname(normalizedName).toLowerCase();
  const label = parse(normalizedName).name.trim();
  if (!label) throw new Error(`音效文件缺少可显示的名称：${entry.name}`);
  if (labels.has(label)) throw new Error(`音效文件名重复：${label}`);
  labels.add(label);
  const id = createHash("sha256").update(normalizedName).digest("hex").slice(0, 16);
  const outputName = `${id}${extension}`;
  const durationMs = Math.min(10_000, Math.max(1_000, Math.ceil(probeSeconds(join(sourceDirectory, entry.name)) * 1000) + 250));
  return { id, label, url: `/quick-phrases/${outputName}`, durationMs, sourceName: entry.name, outputName };
});

await rm(publicDirectory, { recursive: true, force: true });
await mkdir(publicDirectory, { recursive: true });
await mkdir(resolve(clientManifest, ".."), { recursive: true });
await mkdir(resolve(serverManifest, ".."), { recursive: true });

for (const phrase of phrases) {
  await copyFile(join(sourceDirectory, phrase.sourceName), join(publicDirectory, phrase.outputName));
}

const header = "// Generated by scripts/sync-quick-phrases.mjs from assets/audio/quick-phrases/. Do not edit.\n";
const clientRows = phrases.map(({ id, label, url, durationMs }) => `  ${JSON.stringify({ id, label, url, durationMs })},`).join("\n");
const serverRows = phrases.map(({ id, label, durationMs }) => `  ${JSON.stringify({ id, label, durationMs })},`).join("\n");
await writeFile(clientManifest, `${header}export interface QuickPhraseAsset { id: string; label: string; url: string; durationMs: number }\nexport const quickPhrases: readonly QuickPhraseAsset[] = [\n${clientRows}\n];\n`, "utf8");
await writeFile(serverManifest, `${header}export interface QuickPhraseDefinition { id: string; label: string; durationMs: number }\nexport const quickPhrases: readonly QuickPhraseDefinition[] = [\n${serverRows}\n];\n`, "utf8");
await writeFile(join(publicDirectory, "README.txt"), "Generated from the repository root 音效 directory.\n", "utf8");

console.log(`Synced ${phrases.length} quick-phrase audio file(s).`);
